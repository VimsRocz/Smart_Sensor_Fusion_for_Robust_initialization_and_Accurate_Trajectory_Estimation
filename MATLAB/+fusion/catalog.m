tasks{end+1} = make_task(7, 'evaluation', ...
    'Residual evaluation and quality metrics', ...
    ['Reduce the Task 6 overlay to residual time histories and the scalar ' ...
     'metrics used to rank the three methods.'], ...
    { sub('7.1', 'Compute NED position residuals'), ...
      sub('7.2', 'Compute NED velocity residuals'), ...
      sub('7.3', 'Compute the sign-invariant quaternion geodesic error'), ...
      sub('7.4', 'Export the scalar comparison metrics'), ...
      sub('7.6', ['Compare fused and truth states in NED, ECEF, and Body frames ' ...
          'and report detailed attitude errors']) }, ...
    { figt('7.1', 'position_residuals', 'Fused minus truth position residuals', 'NED', {'imu','gnss','truth'}), ...
      figt('7.1', 'position_error_distribution', 'Position error norm distribution', 'NED', {'imu','gnss','truth'}), ...
      figt('7.2', 'velocity_residuals', 'Fused minus truth velocity residuals', 'NED', {'imu','gnss','truth'}), ...
      figt('7.3', 'attitude_error', 'Quaternion geodesic attitude error', 'BODY2NED', {'imu','truth'}), ...
      fig('7.4', 'metric_summary', 'Scalar accuracy metrics for this method', 'NONE', {'imu','gnss','truth'}), ...
      fig('7.4', 'innovation_summary', 'GNSS innovation statistics used when truth is absent', 'NED', {'gnss'}), ...
      figt('7.6', 'fused_vs_truth_ned', 'Fused and truth position and velocity', 'NED', {'imu','gnss','truth'}), ...
      figt('7.6', 'fused_vs_truth_ecef', 'Fused and truth position and velocity', 'ECEF', {'imu','gnss','truth'}), ...
      figt('7.6', 'fused_vs_truth_body', 'Fused and truth position and velocity', 'BODY', {'imu','gnss','truth'}), ...
      figt('7.6', 'quaternion_truth_vs_estimate', 'Body-to-NED quaternion truth versus estimate', 'BODY2NED', {'imu','truth'}), ...
      figt('7.6', 'quaternion_error_components', 'Body-to-NED quaternion component errors', 'BODY2NED', {'imu','truth'}), ...
      figt('7.6', 'euler_error_over_time', 'Body-to-NED Euler angle errors', 'BODY2NED', {'imu','truth'}), ...
      figt('7.6', 'attitude_error_angle', 'Sign-invariant total attitude error angle', 'BODY2NED', {'imu','truth'}) });

c.tasks = [tasks{:}];
c.comparison_slug = 'comparison';
c.comparison_figures = { ...
    fig('C.1', 'initial_attitude_by_method', 'Initial attitude solved by each method', 'BODY2NED', {'imu','gnss'}), ...
    fig('C.2', 'fused_position_by_method', 'Fused position from each method', 'NED', {'imu','gnss'}), ...
    figt('C.3', 'position_error_by_method', 'Position error norm from each method', 'NED', {'imu','gnss','truth'}), ...
    figt('C.4', 'attitude_error_by_method', 'Attitude error from each method', 'BODY2NED', {'imu','truth'}), ...
    fig('C.5', 'metric_bars_by_method', 'Task 7 metrics side by side', 'NONE', {'imu','gnss','truth'}) };

validate_catalog(c);
cached = c;
end

% ---------------------------------------------------------------------------
function s = sub(number, name)
s = struct('number', number, 'name', name);
end

function s = fig(subtask, slug, title, frame, sources)
s = struct('subtask', subtask, 'slug', slug, 'title', title, ...
    'frame', frame, 'sources', {sources}, 'requires_truth', false);
end

function s = figt(subtask, slug, title, frame, sources)
s = fig(subtask, slug, title, frame, sources);
s.requires_truth = true;
end

function t = make_task(number, slug, name, purpose, subtasks, figures)
t = struct('number', number, 'slug', slug, 'name', name, 'purpose', purpose, ...
    'directory', sprintf('task_%02d_%s', number, slug), ...
    'subtasks', {subtasks}, 'figures', {figures});
end

function validate_catalog(c)
frameTags = c.frames(:, 1);
for k = 1:numel(c.tasks)
    task = c.tasks(k);
    if task.number ~= k
        error('fusion:Catalog', 'Tasks must be numbered 1..N in order.');
    end
    declared = cellfun(@(s) string(s.number), task.subtasks);
    slugs = cellfun(@(f) string(f.slug), task.figures);
    if numel(unique(slugs)) ~= numel(slugs)
        error('fusion:Catalog', 'Task %d has duplicate figure slugs.', task.number);
    end
    for j = 1:numel(task.figures)
        f = task.figures{j};
        if ~any(declared == string(f.subtask))
            error('fusion:Catalog', 'Task %d figure %s references undeclared subtask %s.', ...
                task.number, f.slug, f.subtask);
        end
        if ~any(strcmp(frameTags, f.frame))
            error('fusion:Catalog', 'Figure %s uses unknown frame %s.', f.slug, f.frame);
        end
    end
end
end
