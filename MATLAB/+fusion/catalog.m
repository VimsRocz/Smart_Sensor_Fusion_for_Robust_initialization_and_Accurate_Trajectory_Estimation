function c = catalog()
%CATALOG Task, subtask and figure catalog shared with the Python pipeline.
%
%   This mirrors PYTHON/fusion_pipeline/catalog.py. Both implementations must
%   produce the same directory names and the same figure filenames, so any
%   change here needs the same change there (and vice versa).
%
%   c.frames  Nx2 cellstr of {tag, meaning}
%   c.tasks   1xN struct array with fields:
%               number, slug, name, purpose, directory
%               subtasks : cell array of struct('number','name')
%               figures  : cell array of struct('subtask','slug','title',
%                                               'frame','sources','requires_truth')
%   c.comparison_slug     directory name for the cross-method comparison
%   c.comparison_figures  cell array of figure structs

persistent cached
if ~isempty(cached)
    c = cached;
    return
end

c.frames = { ...
    'ECEF',      'Earth-Centred Earth-Fixed (WGS-84), metres'; ...
    'GEODETIC',  'Geodetic WGS-84 latitude/longitude/altitude'; ...
    'BODY',      'IMU body frame (x-forward, y-right, z-down)'; ...
    'NED',       'Local-level North-East-Down at the Task 1 origin'; ...
    'BODY2NED',  'Body-to-NED rotation (quaternion / Euler / DCM)'; ...
    'BODYvsNED', 'Measured body vectors against their NED references'; ...
    'NONE',      'Frame-independent quantity'};

tasks = {};

tasks{end+1} = make_task(1, 'inputs_reference', ...
    'Inputs and navigation reference', ...
    ['Validate every input file against the documented contract and build ' ...
     'the WGS-84 reference used by all later tasks.'], ...
    { sub('1.1', 'Validate IMU, GNSS and truth structure, units and timing'), ...
      sub('1.2', 'Derive the WGS-84 origin and ECEF to NED rotation from the first GNSS fix'), ...
      sub('1.3', 'Compute local normal gravity and the Earth-rotation vector in NED') }, ...
    { fig('1.1', 'input_time_coverage', 'Input time coverage and sample rates', 'NONE', {'imu','gnss','truth'}), ...
      fig('1.1', 'gnss_raw_position_velocity', 'Raw GNSS position and velocity as supplied', 'ECEF', {'gnss'}), ...
      fig('1.1', 'imu_raw_rates', 'IMU angular rate and specific force after unit handling', 'BODY', {'imu'}), ...
      fig('1.2', 'reference_origin_map', 'Reference origin on the WGS-84 graticule', 'GEODETIC', {'gnss'}), ...
      fig('1.3', 'gravity_earth_rate_vectors', 'Reference gravity and Earth-rate vectors', 'NED', {'gnss'}) });

tasks{end+1} = make_task(2, 'static_imu', ...
    'Static interval and measured body vectors', ...
    ['Find the quietest stretch of IMU data and average it into the two body ' ...
     'vectors that Wahba''s problem needs.'], ...
    { sub('2.1', 'Convert delta-angle/delta-velocity increments into SI rates'), ...
      sub('2.2', 'Select the minimum-variance static window'), ...
      sub('2.3', 'Average and normalise the specific-force and Earth-rate body vectors') }, ...
    { fig('2.1', 'converted_rates', 'IMU angular rate and specific force used by Task 2', 'BODY', {'imu'}), ...
      fig('2.2', 'static_window_variance_scan', 'Rolling-variance detector across the whole log', 'BODY', {'imu'}), ...
      fig('2.2', 'static_window_selection', 'Selected static window on the IMU record', 'BODY', {'imu'}), ...
      fig('2.3', 'mean_body_vs_reference_vectors', 'Averaged body vectors against their NED references', 'BODYvsNED', {'imu','gnss'}) });

tasks{end+1} = make_task(3, 'attitude_init', ...
    'Initial attitude and IMU biases', ...
    ['Solve Wahba''s problem with the selected method and turn the resulting ' ...
     'attitude into accelerometer and gyroscope bias estimates.'], ...
    { sub('3.1', 'Solve the Body-to-NED alignment with TRIAD, Davenport or SVD'), ...
      sub('3.2', 'Project onto SO(3) and normalise the scalar-first quaternion'), ...
      sub('3.3', 'Estimate accelerometer and gyroscope bias in the solved attitude') }, ...
    { fig('3.1', 'rotation_matrix', 'Solved Body-to-NED direction cosine matrix', 'BODY2NED', {'imu','gnss'}), ...
      fig('3.1', 'vector_alignment_error', 'Residual alignment error per observed vector', 'BODY2NED', {'imu','gnss'}), ...
      fig('3.2', 'initial_quaternion', 'Initial quaternion components [w,x,y,z]', 'BODY2NED', {'imu','gnss'}), ...
      fig('3.2', 'initial_euler_angles', 'Initial yaw, pitch and roll', 'BODY2NED', {'imu','gnss'}), ...
      fig('3.3', 'imu_bias_estimates', 'Estimated accelerometer and gyroscope bias', 'BODY', {'imu'}) });

tasks{end+1} = make_task(4, 'inertial_propagation', ...
    'IMU-only strapdown propagation', ...
    ['Integrate the bias-corrected IMU alone so the inertial solution can be ' ...
     'judged before GNSS is allowed to correct it.'], ...
    { sub('4.1', 'Screen physical-range outliers and remove the Task 3 biases'), ...
      sub('4.2', 'Propagate the Body-to-NED quaternion with Earth and transport rates'), ...
      sub('4.3', 'Apply Coriolis compensation and integrate the NED state'), ...
      sub('4.6', ['Compare GNSS-derived and IMU-derived position, velocity, and ' ...
          'acceleration in NED, ECEF, and Body frames']) }, ...
    { fig('4.1', 'range_screening', 'Specific-force and angular-rate magnitudes against their limits', 'BODY', {'imu'}), ...
      fig('4.1', 'bias_corrected_imu', 'IMU signals before and after bias removal', 'BODY', {'imu'}), ...
      fig('4.2', 'propagated_quaternion', 'Propagated Body-to-NED quaternion history', 'BODY2NED', {'imu'}), ...
      fig('4.2', 'propagated_euler_angles', 'Propagated yaw, pitch and roll history', 'BODY2NED', {'imu'}), ...
      fig('4.3', 'imu_only_position_velocity', 'IMU-only position and velocity', 'NED', {'imu'}), ...
      fig('4.3', 'imu_only_acceleration', 'IMU-only resolved acceleration', 'NED', {'imu'}), ...
      fig('4.3', 'imu_only_ground_track', 'IMU-only horizontal ground track', 'NED', {'imu'}), ...
      fig('4.6', 'gnss_vs_imu_ned', 'GNSS-derived versus IMU-derived kinematics', 'NED', {'imu','gnss'}), ...
      fig('4.6', 'gnss_vs_imu_ecef', 'GNSS-derived versus IMU-derived kinematics', 'ECEF', {'imu','gnss'}), ...
      fig('4.6', 'gnss_vs_imu_body', 'GNSS-derived versus IMU-derived kinematics', 'BODY', {'imu','gnss'}) });

tasks{end+1} = make_task(5, 'gnss_imu_fusion', ...
    'GNSS/IMU Kalman fusion', ...
    ['Run the six-state position/velocity filter that corrects the inertial ' ...
     'solution at every GNSS epoch.'], ...
    { sub('5.1', 'Predict the six-state NED position/velocity from IMU acceleration'), ...
      sub('5.2', 'Apply Joseph-form updates at each asynchronous GNSS epoch'), ...
      sub('5.3', 'Export the fused state and the innovation history'), ...
      sub('5.10', ['Present the final fused position, velocity, and acceleration ' ...
          'in NED, ECEF, and Body frames']) }, ...
    { fig('5.1', 'prediction_vs_gnss', 'Filter prediction against the GNSS measurements', 'NED', {'imu','gnss'}), ...
      fig('5.2', 'kalman_innovations', 'Position and velocity innovations at each update', 'NED', {'gnss'}), ...
      fig('5.3', 'fused_position_velocity', 'Fused position and velocity', 'NED', {'imu','gnss'}), ...
      fig('5.3', 'fused_ground_track', 'Fused horizontal ground track with GNSS fixes', 'NED', {'imu','gnss'}), ...
      fig('5.3', 'fused_vs_imu_only', 'Fused solution against the IMU-only solution', 'NED', {'imu','gnss'}), ...
      fig('5.10', 'fused_state_ned', 'Final fused position, velocity, and acceleration', 'NED', {'imu','gnss'}), ...
      fig('5.10', 'fused_state_ecef', 'Final fused position, velocity, and acceleration', 'ECEF', {'imu','gnss'}), ...
      fig('5.10', 'fused_state_body', 'Final fused position, velocity, and acceleration', 'BODY', {'imu','gnss'}) });

tasks{end+1} = make_task(6, 'truth_overlay', ...
    'Truth overlay in a common frame', ...
    ['Put truth and estimate in one frame, one time base, and one quaternion ' ...
     'convention before anything is compared.'], ...
    { sub('6.1', 'Restrict to the common time range and apply the attitude-only time offset'), ...
      sub('6.2', 'Convert truth ECEF position/velocity with the Task 1 origin and rotation'), ...
      sub('6.3', 'Compare relative height defined as negative NED Down'), ...
      sub('6.4', 'Normalise and hemisphere-align the Body-to-NED quaternions') }, ...
    { figt('6.1', 'truth_time_alignment', 'Truth and estimate time coverage after alignment', 'NONE', {'imu','truth'}), ...
      figt('6.2', 'fused_vs_truth_position_velocity', 'Fused and truth position and velocity', 'NED', {'imu','gnss','truth'}), ...
      figt('6.2', 'fused_vs_truth_ground_track', 'Fused and truth horizontal ground track', 'NED', {'imu','gnss','truth'}), ...
      figt('6.3', 'height_above_origin', 'Relative height, defined as negative NED Down', 'NED', {'imu','gnss','truth'}), ...
